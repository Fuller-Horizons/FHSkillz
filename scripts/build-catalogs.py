#!/usr/bin/env python3
"""build-catalogs.py — keep every non-Claude install channel in step with the repo.

Writes (or with --check, verifies) three generated files from skills/ and
.claude-plugin/marketplace.json, so a tested release on main reaches every tool:

  .codex-plugin/plugin.json        Codex CLI plugin manifest (skills: ./skills/)
  .agents/plugins/marketplace.json Codex repo-scoped marketplace (one plugin: this repo)
  skills/index.json                OpenCode HTTP skill catalog (name, version, files)
  docs/SKILL-INDEX.md              one-screen map of every skill, read instead of opening each SKILL.md

Versions come from the Claude manifest (plugin) and each SKILL.md's
metadata.version (skills), so a version bump is what tells Codex and OpenCode
to refresh. Repo tooling (infrastructure), not skill content. Stdlib only.
Usage: build-catalogs.py [--check]   (exit 1 on --check when a file is stale)
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKIP_FILES = {"README.md", "CHANGELOG.md"}
SKIP_DIRS = {"tests", "__pycache__", ".pytest_cache"}


def skill_version(path):
    m = re.search(r"^\s*version:\s*['\"]?([0-9][^'\"\s]*)", open(path, encoding="utf-8").read(), re.M)
    return m.group(1) if m else "0.0.0"


def build():
    mp = json.load(open(os.path.join(ROOT, ".claude-plugin", "marketplace.json")))
    plug = mp["plugins"][0]
    cp = json.load(open(os.path.join(ROOT, ".claude-plugin", "plugin.json")))
    codex_plugin = {
        "name": plug["name"],
        "version": plug["version"],
        "description": cp.get("description", plug.get("description", "")),
        "author": {k: v for k, v in cp.get("author", {}).items() if k in ("name", "url")},
        "homepage": cp.get("homepage", "https://github.com/Fuller-Horizons/FHSkillz"),
        "repository": "https://github.com/Fuller-Horizons/FHSkillz",
        "skills": "./skills/",
        "interface": {"displayName": "FHSkillz", "shortDescription": "Fuller Horizons consulting skills",
                      "developerName": "Fuller Horizons", "category": "Productivity"},
    }
    codex_market = {
        "name": plug["name"],
        "interface": {"displayName": "FHSkillz (Fuller Horizons)"},
        "plugins": [{"name": plug["name"], "source": {"source": "local", "path": "./"},
                     "policy": {"installation": "AVAILABLE"}, "category": "Productivity"}],
    }
    skills = []
    sdir = os.path.join(ROOT, "skills")
    for name in sorted(os.listdir(sdir)):
        d = os.path.join(sdir, name)
        if not os.path.isfile(os.path.join(d, "SKILL.md")):
            continue
        files = []
        for root, dirs, fs in os.walk(d):
            dirs[:] = sorted(x for x in dirs if x not in SKIP_DIRS)
            for f in sorted(fs):
                rel = os.path.relpath(os.path.join(root, f), d).replace(os.sep, "/")
                if rel in SKIP_FILES or f.endswith((".pyc",)):
                    continue
                files.append(rel)
        files.sort(key=lambda x: (x != "SKILL.md", x))
        skills.append({"name": name, "version": skill_version(os.path.join(d, "SKILL.md")), "files": files})
    rows = []
    for sk in skills:
        txt = open(os.path.join(sdir, sk["name"], "SKILL.md"), encoding="utf-8").read()
        m = re.search(r"^description:\s*>-?\s*\n((?:[ \t]+.*\n)+)", txt, re.M) or re.search(r"^description:\s*(.+)$", txt, re.M)
        desc = " ".join(m.group(1).split()) if m else ""
        use, _, dont = desc.partition("Do NOT use")
        lines = txt.count("\n")
        rows.append(f"| {sk['name']} | {sk['version']} | {lines} | {use.strip()} | {('Do NOT use' + dont).strip() if dont else ''} |")
    index_md = ("# FHSkillz skill index (generated)\n\n"
                "Generated by `scripts/build-catalogs.py` from each SKILL.md; do not edit by hand. "
                f"Plugin {plug['version']} · {len(skills)} skills. Read this to learn the suite; open a skill's "
                "SKILL.md only when you are changing or running that skill.\n\n"
                "| Skill | Version | Lines | Use for | Not for |\n|---|---|---|---|---|\n" + "\n".join(rows) + "\n")
    return {
        os.path.join("docs", "SKILL-INDEX.md"): index_md,
        os.path.join(".codex-plugin", "plugin.json"): codex_plugin,
        os.path.join(".agents", "plugins", "marketplace.json"): codex_market,
        os.path.join("skills", "index.json"): {"skills": skills},
    }


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for rel, data in build().items():
        path = os.path.join(ROOT, rel)
        text = data if isinstance(data, str) else json.dumps(data, indent=2) + "\n"
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if old == text:
            continue
        if check:
            stale.append(rel)
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            open(path, "w", encoding="utf-8").write(text)
            print(f"build-catalogs: wrote {rel}")
    if check and stale:
        print("build-catalogs: stale, run scripts/build-catalogs.py: " + ", ".join(stale))
        return 1
    if check:
        print("build-catalogs: skill index and Codex/OpenCode catalogs are current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
