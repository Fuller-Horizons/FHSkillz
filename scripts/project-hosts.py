#!/usr/bin/env python3
"""Project skills/<name>/SKILL.md into other agent-host layouts (stdlib only).

Currently supported host: codex  ->  .agents/skills/<name>/SKILL.md

Usage:
  python3 scripts/project-hosts.py [--hosts codex] [--root DIR]
  python3 scripts/project-hosts.py --check [--hosts codex] [--root DIR]
"""
import argparse
import os
import re
import shutil
import sys

KEY_RE = re.compile(r"^([A-Za-z0-9_-]+):")
FENCE_RE = re.compile(r"^(\s*)(`{3,}|~{3,})\s*([^\s`]*)")
EXEC_LANGS = {"bash", "sh", "zsh", "shell"}
COPY_DIRS = ("references", "assets", "prompts")
SUBST_RE = re.compile(r"\$\{CLAUDE_PLUGIN_ROOT\}|\$\{CLAUDE_SKILL_DIR\}|\$ARGUMENTS\b")
README_LINE = ("<!-- Generated by scripts/project-hosts.py from skills/ — "
               "do not edit; run `python3 scripts/project-hosts.py` to regenerate. -->")


def split_frontmatter(text):
    """Return (frontmatter_lines, body) or (None, text) when absent."""
    lines = text.split("\n")
    if not lines or lines[0].strip() != "---":
        return None, text
    for i in range(1, len(lines)):
        if lines[i].strip() == "---":
            return lines[1:i], "\n".join(lines[i + 1:])
    return None, text


def filter_frontmatter(fm_lines, keep):
    """Keep only top-level keys in `keep`, preserving each block verbatim."""
    out, keeping = [], False
    for line in fm_lines:
        m = KEY_RE.match(line)
        if m:
            keeping = m.group(1) in keep
        if keeping:
            out.append(line)
    return out


def rewrite_fences(body, rel_skill, rel_root):
    """Rewrite Claude-only substitutions inside executable fences."""
    def sub(m):
        tok = m.group(0)
        if tok == "${CLAUDE_PLUGIN_ROOT}":
            return rel_root
        if tok == "${CLAUDE_SKILL_DIR}":
            return rel_skill
        return '"<args>"'

    out, fence = [], None  # fence = (char, length, executable)
    for line in body.split("\n"):
        m = FENCE_RE.match(line)
        if fence is None:
            if m:
                fence = (m.group(2)[0], len(m.group(2)), m.group(3).lower() in EXEC_LANGS)
            out.append(line)
            continue
        if m and m.group(2)[0] == fence[0] and len(m.group(2)) >= fence[1] and not m.group(3):
            fence = None
            out.append(line)
            continue
        out.append(SUBST_RE.sub(sub, line) if fence[2] else line)
    return "\n".join(out)


def find_exec_substitutions(text):
    """Return [(lineno, token)] of Claude-only substitutions inside executable fences."""
    found, fence = [], None
    for n, line in enumerate(text.split("\n"), 1):
        m = FENCE_RE.match(line)
        if fence is None:
            if m:
                fence = (m.group(2)[0], len(m.group(2)), m.group(3).lower() in EXEC_LANGS)
            continue
        if m and m.group(2)[0] == fence[0] and len(m.group(2)) >= fence[1] and not m.group(3):
            fence = None
            continue
        if fence[2]:
            for t in SUBST_RE.finditer(line):
                found.append((n, t.group(0)))
    return found


class CodexHost:
    name = "codex"
    out_rel = os.path.join(".agents", "skills")
    keep = ("name", "description", "metadata", "license", "allowed-tools")

    def copy_scripts(self, skill):
        return skill.startswith("jail-py-")

    def project_skill_md(self, skill, text):
        fm, body = split_frontmatter(text)
        if fm is None:
            fm_out, body = [], text
        else:
            fm_out = filter_frontmatter(fm, self.keep)
        body = rewrite_fences(body, ".", "../../..")
        header = ("<!-- Generated by scripts/project-hosts.py from skills/%s/SKILL.md "
                  "— do not edit -->" % skill)
        body = body.lstrip("\n")
        return "---\n" + "\n".join(fm_out) + "\n---\n" + header + "\n\n" + body

    def readme(self):
        return (README_LINE + "\n\n# Codex skill projections\n\n"
                "Each folder here is generated from `skills/<name>/` for hosts that read "
                "`.agents/skills/`. Edit the source skill, then regenerate.\n")


HOSTS = {"codex": CodexHost}


def read_text(path):
    with open(path, encoding="utf-8", newline="") as f:
        return f.read()


def list_skills(root):
    sdir = os.path.join(root, "skills")
    if not os.path.isdir(sdir):
        return []
    return sorted(d for d in os.listdir(sdir)
                  if os.path.isfile(os.path.join(sdir, d, "SKILL.md")))


def expected_files(root, host):
    """Map relative-path-under-root -> bytes for everything the host projection contains."""
    files = {}
    base = host.out_rel
    files[os.path.join(base, "README.md")] = host.readme().encode("utf-8")
    for skill in list_skills(root):
        src = os.path.join(root, "skills", skill)
        text = read_text(os.path.join(src, "SKILL.md"))
        files[os.path.join(base, skill, "SKILL.md")] = host.project_skill_md(skill, text).encode("utf-8")
        subdirs = list(COPY_DIRS) + (["scripts"] if host.copy_scripts(skill) else [])
        for sub in subdirs:
            sroot = os.path.join(src, sub)
            if not os.path.isdir(sroot):
                continue
            for dp, dn, fn in os.walk(sroot):
                dn.sort()
                for f in sorted(fn):
                    if f.endswith((".pyc",)) or "__pycache__" in dp:
                        continue
                    full = os.path.join(dp, f)
                    rel = os.path.relpath(full, src)
                    with open(full, "rb") as fh:
                        files[os.path.join(base, skill, rel)] = fh.read()
    return files


def existing_files(root, host):
    out = set()
    base = os.path.join(root, host.out_rel)
    for dp, _, fn in os.walk(base):
        for f in fn:
            out.add(os.path.relpath(os.path.join(dp, f), root))
    return out


def generate(root, host):
    exp = expected_files(root, host)
    base = os.path.join(root, host.out_rel)
    # remove stale files in managed tree
    for rel in existing_files(root, host) - set(exp):
        os.remove(os.path.join(root, rel))
    for dp, dn, fn in os.walk(base, topdown=False):
        if not dn and not fn and dp != base:
            os.rmdir(dp)
    for rel, data in exp.items():
        path = os.path.join(root, rel)
        if os.path.isfile(path):
            with open(path, "rb") as f:
                if f.read() == data:
                    continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "wb") as f:
            f.write(data)
    return len([r for r in exp if r.endswith("SKILL.md")])


def check(root, host):
    findings = []
    exp = expected_files(root, host)
    have = existing_files(root, host)
    for rel in sorted(exp):
        path = os.path.join(root, rel)
        if not os.path.isfile(path):
            findings.append("[%s] missing: %s" % (host.name, rel))
            continue
        with open(path, "rb") as f:
            if f.read() != exp[rel]:
                findings.append("[%s] stale: %s" % (host.name, rel))
    for rel in sorted(have - set(exp)):
        findings.append("[%s] orphan (no source): %s" % (host.name, rel))
    for rel in sorted(have):
        if rel.endswith("SKILL.md"):
            for n, tok in find_exec_substitutions(read_text(os.path.join(root, rel))):
                findings.append("[%s] Claude-only substitution %s in executable fence: %s:%d"
                                % (host.name, tok, rel, n))
    return findings


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="verify projections; exit 1 on drift")
    ap.add_argument("--hosts", default="codex", help="comma-separated hosts (supported: codex)")
    ap.add_argument("--root", default=os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                    help="repo root (default: parent of scripts/)")
    args = ap.parse_args(argv)
    names = [h.strip() for h in args.hosts.split(",") if h.strip()]
    bad = [h for h in names if h not in HOSTS]
    if bad:
        print("unsupported host(s): %s (supported: %s)" % (", ".join(bad), ", ".join(sorted(HOSTS))),
              file=sys.stderr)
        return 2
    rc = 0
    for n in names:
        host = HOSTS[n]()
        if args.check:
            findings = check(args.root, host)
            for f in findings:
                print(f)
            if findings:
                rc = 1
            else:
                print("[%s] OK: %d skills in sync" % (n, len(list_skills(args.root))))
        else:
            count = generate(args.root, host)
            print("[%s] projected %d skills -> %s" % (n, count, host.out_rel))
    return rc


if __name__ == "__main__":
    sys.exit(main())
