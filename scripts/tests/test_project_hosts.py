import importlib.util
import os
import shutil
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
SCRIPT = os.path.join(os.path.dirname(HERE), "project-hosts.py")
FIXTURE = os.path.join(HERE, "fixtures", "hosts")

spec = importlib.util.spec_from_file_location("project_hosts", SCRIPT)
ph = importlib.util.module_from_spec(spec)
spec.loader.exec_module(ph)


def read(p):
    with open(p, encoding="utf-8") as f:
        return f.read()


class ProjectHostsTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp()
        self.root = os.path.join(self.tmp, "repo")
        shutil.copytree(FIXTURE, self.root)
        self.out = os.path.join(self.root, ".agents", "skills")

    def tearDown(self):
        shutil.rmtree(self.tmp, ignore_errors=True)

    def run_main(self, *a):
        return ph.main(["--root", self.root] + list(a))

    def test_generation(self):
        self.assertEqual(self.run_main(), 0)
        text = read(os.path.join(self.out, "demo-skill", "SKILL.md"))
        fm = text.split("---")[1]
        self.assertIn("name: demo-skill", fm)
        self.assertIn("metadata:\n  version: 1.0.0", fm)
        self.assertIn("description: >-\n  A fixture skill", fm)
        self.assertIn("allowed-tools: Read, Bash", fm)
        self.assertNotIn("model:", fm)
        self.assertNotIn("argument-hint", fm)
        self.assertIn("<!-- Generated by scripts/project-hosts.py from skills/demo-skill/SKILL.md", text)
        self.assertIn("python3 ../../../scripts/tool.py --in ./references/r.md \"<args>\"", text)
        self.assertIn("Prose mention of ${CLAUDE_PLUGIN_ROOT} stays", text)  # prose untouched
        self.assertIn('print("${CLAUDE_SKILL_DIR}")', text)  # python fence untouched
        self.assertTrue(os.path.isfile(os.path.join(self.out, "demo-skill", "references", "r.md")))
        self.assertFalse(os.path.exists(os.path.join(self.out, "demo-skill", "scripts")))
        self.assertTrue(os.path.isfile(os.path.join(self.out, "jail-py-demo", "scripts", "run.py")))
        self.assertTrue(read(os.path.join(self.out, "README.md")).startswith("<!-- Generated"))

    def test_idempotent(self):
        self.run_main()
        p = os.path.join(self.out, "demo-skill", "SKILL.md")
        m1 = os.stat(p).st_mtime_ns
        before = read(p)
        self.run_main()
        self.assertEqual(before, read(p))
        self.assertEqual(m1, os.stat(p).st_mtime_ns)
        self.assertEqual(self.run_main("--check"), 0)

    def test_check_fails_when_missing(self):
        self.assertEqual(self.run_main("--check"), 1)

    def test_check_fails_on_stale(self):
        self.run_main()
        src = os.path.join(self.root, "skills", "demo-skill", "SKILL.md")
        with open(src, "a", encoding="utf-8") as f:
            f.write("\nmore\n")
        self.assertEqual(self.run_main("--check"), 1)
        self.run_main()
        self.assertEqual(self.run_main("--check"), 0)

    def test_check_flags_substitution_in_fence(self):
        self.run_main()
        p = os.path.join(self.out, "demo-skill", "SKILL.md")
        with open(p, "a", encoding="utf-8") as f:
            f.write("\n```bash\nls ${CLAUDE_PLUGIN_ROOT}\n```\n")
        self.assertEqual(self.run_main("--check"), 1)

    def test_unsupported_host(self):
        self.assertEqual(self.run_main("--hosts", "cursor"), 2)


if __name__ == "__main__":
    unittest.main()
